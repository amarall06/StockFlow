import {test,expect} from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import {prepareKeyboardPage as prepareBase} from './helpers/keyboard'
async function prepareKeyboardPage(page){const writes=await prepareBase(page);await page.getByLabel('Dados do gráfico de capacidade').selectOption('demo');return writes}
const region=page=>page.getByRole('region',{name:'Ocupação por capacidade física'})
async function edit(page,location,boxes,basis='Caixa padrão de teste'){
  await region(page).getByRole('button',{name:`Configurar capacidade de ${location}`,exact:true}).click()
  const dialog=page.getByRole('dialog',{name:`Capacidade de ${location}`,exact:true})
  await dialog.getByLabel('Capacidade física (caixas)',{exact:true}).fill(boxes)
  if(boxes!=='')await dialog.getByLabel('Referência de tamanho da caixa').fill(basis)
  return dialog
}
test('demonstração usa as quatro prateleiras e capacidade fixa, com excesso numérico acima de 100%',async({page})=>{
  const writes=await prepareKeyboardPage(page), chart=region(page)
  await expect(chart).toContainText('Prateleiras Norte, Sul, Leste e Oeste')
  await expect(chart.getByRole('article',{name:'Prateleira NORTE',exact:true})).toContainText('100% da capacidade')
  await expect(chart.getByRole('article',{name:'Prateleira SUL',exact:true})).toContainText('20% da capacidade')
  const east=chart.getByRole('article',{name:'Prateleira LESTE',exact:true})
  await expect(east).toContainText('110% da capacidade');await expect(east).toContainText('Acima da capacidade informada em 3 caixas')
  await expect(east.getByRole('meter')).toHaveAttribute('aria-valuetext',/110%/)
  await expect(east.locator('.capacity-track>span')).toHaveAttribute('style','width: 100%;')
  await expect(chart.getByRole('article',{name:'Prateleira OESTE',exact:true})).toContainText('0% da capacidade')
  expect(writes).toEqual([])
})
test('edição fictícia persiste e não preenche capacidades do estoque consultado',async({page})=>{
  const writes=await prepareKeyboardPage(page)
  const dialog=await edit(page,'NORTE','80');await dialog.getByRole('button',{name:'Salvar capacidade local'}).click()
  await expect(region(page).getByRole('article',{name:'Prateleira NORTE',exact:true})).toContainText('50% da capacidade')
  await page.reload();await expect(region(page).getByRole('article',{name:'Prateleira NORTE',exact:true})).toContainText('50% da capacidade')
  await region(page).getByLabel('Dados do gráfico de capacidade').selectOption('stock')
  await expect(region(page)).toContainText('Capacidade não informada — percentual indisponível')
  await expect(region(page).getByRole('meter')).toHaveCount(0)
  expect(writes).toEqual([])
})
test('consulta soma molas e amortecedores e permite remover a capacidade sem inventar percentual',async({page})=>{
  const writes=await prepareKeyboardPage(page)
  await region(page).getByLabel('Dados do gráfico de capacidade').selectOption('stock')
  let dialog=await edit(page,'A01','10');await dialog.getByRole('button',{name:'Salvar capacidade local'}).click()
  await expect(region(page)).toContainText('50% da capacidade')
  await page.getByText('Filtros do painel',{exact:true}).click();await page.getByLabel('Filtrar indicadores').selectOption('springs')
  await expect(region(page)).toContainText('50% da capacidade')
  dialog=await edit(page,'A01','');await dialog.getByRole('button',{name:'Salvar capacidade local'}).click()
  await expect(region(page)).toContainText('Capacidade não informada')
  await expect(region(page).getByRole('meter')).toHaveCount(0)
  expect(writes).toEqual([])
})
test('falha de gravação e mudança de outra aba preservam a capacidade salva',async({page})=>{
  await prepareKeyboardPage(page)
  const dialog=await edit(page,'NORTE','90')
  await page.evaluate(()=>{const key='liber:shelf-capacity:v1:demo:11111111-1111-4111-8111-111111111111';localStorage.setItem(key,JSON.stringify({version:1,userId:'11111111-1111-4111-8111-111111111111',entries:{NORTE:{boxes:100,basis:'Outra aba'}}}));window.dispatchEvent(new Event('storage'))})
  await dialog.getByRole('button',{name:'Salvar capacidade local'}).click()
  await expect(dialog.getByRole('alert')).toContainText('outra aba')
  await dialog.getByRole('button',{name:'Fechar capacidade'}).click()
  await expect(region(page).getByRole('article',{name:'Prateleira NORTE',exact:true})).toContainText('40% da capacidade')
  const second=await edit(page,'NORTE','80')
  await page.evaluate(()=>{const original=Storage.prototype.setItem;Storage.prototype.setItem=function(key,value){if(key.startsWith('liber:shelf-capacity:'))throw Error('Sem espaço para capacidade');return original.call(this,key,value)}})
  await second.getByRole('button',{name:'Salvar capacidade local'}).click();await expect(second.getByRole('alert')).toContainText('Sem espaço')
})
for(const theme of ['light','dark'])test(`capacidade em 375 px com teclado e acessibilidade A/AA no tema ${theme}`,async({page})=>{
  await page.setViewportSize({width:375,height:812});await page.addInitScript(value=>localStorage.setItem('liber-automotive-theme',value),theme)
  await prepareKeyboardPage(page)
  const audit=await new AxeBuilder({page}).include('.shelf-capacity').withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();expect(audit.violations.map(row=>({id:row.id,targets:row.nodes.map(node=>node.target)}))).toEqual([])
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  const opener=region(page).getByRole('button',{name:'Configurar capacidade de NORTE',exact:true});await opener.focus();await page.keyboard.press('Enter')
  const dialog=page.getByRole('dialog',{name:'Capacidade de NORTE',exact:true});await expect(dialog.getByRole('button',{name:'Fechar capacidade'})).toBeFocused()
  await page.keyboard.press('Tab');await expect(dialog.getByLabel('Capacidade física (caixas)',{exact:true})).toBeFocused()
  const modalAudit=await new AxeBuilder({page}).include('.capacity-dialog').withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();expect(modalAudit.violations.map(row=>row.id)).toEqual([])
  await page.keyboard.press('Escape');await expect(opener).toBeFocused()
})
