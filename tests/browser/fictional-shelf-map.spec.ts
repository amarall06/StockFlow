import {test,expect} from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import {prepareKeyboardPage} from './helpers/keyboard'
const map=page=>page.getByRole('region',{name:'Mapa fictício das prateleiras',exact:true})
const shelf=(page,code)=>map(page).getByRole('button',{name:new RegExp(`^Prateleira ${code} —`)})
test('disposição e detalhes fictícios mantêm os quatro pontos e situações sem depender só de cor',async({page})=>{
  const writes=await prepareKeyboardPage(page)
  const close=page.getByRole('button',{name:'Fechar aviso de estoque',exact:true});if(await close.isVisible())await close.click()
  await expect(map(page)).toContainText('Não representa a planta real')
  const north=await shelf(page,'NORTE').boundingBox(),south=await shelf(page,'SUL').boundingBox(),west=await shelf(page,'OESTE').boundingBox(),east=await shelf(page,'LESTE').boundingBox()
  expect(north!.y).toBeLessThan(west!.y);expect(south!.y).toBeGreaterThan(east!.y);expect(west!.x).toBeLessThan(east!.x)
  await shelf(page,'NORTE').click()
  const table=map(page).getByRole('table',{name:'Produtos fictícios de NORTE'})
  await expect(table).toContainText('Aguardando testagem');await expect(table).toContainText('Liberado para venda')
  await shelf(page,'OESTE').click();await expect(map(page).getByRole('region',{name:'Detalhes da prateleira fictícia',exact:true})).toContainText('Nenhuma caixa registrada')
  expect(writes).toEqual([])
})
test('busca destaca todos os locais do código e ausência não transforma prateleiras em vazias',async({page})=>{
  await prepareKeyboardPage(page)
  const input=map(page).getByLabel('Buscar produto no mapa fictício')
  await input.fill('  agm-35 ')
  await expect(map(page).getByRole('status')).toContainText('NORTE, LESTE')
  await expect(map(page).locator('.map-match')).toHaveCount(2)
  await input.fill('MGM');await expect(map(page).locator('.map-match')).toHaveCount(1);await expect(shelf(page,'SUL')).toHaveAccessibleName(/produto encontrado: 12 caixas/)
  await input.fill('não existe');await expect(map(page).getByRole('status')).toContainText('Nenhum produto encontrado')
  await expect(shelf(page,'NORTE')).toContainText('40 caixas fictícias')
  await map(page).getByRole('button',{name:'Limpar busca do mapa'}).click();await expect(map(page).locator('.map-match')).toHaveCount(0)
})
test('contagem divergente permanece distinta da capacidade editada e mapa só aparece na demonstração',async({page})=>{
  await prepareKeyboardPage(page)
  const close=page.getByRole('button',{name:'Fechar aviso de estoque',exact:true});if(await close.isVisible())await close.click()
  await shelf(page,'LESTE').click()
  const details=map(page).getByRole('region',{name:'Detalhes da prateleira fictícia',exact:true})
  await expect(details).toContainText('referência 33, contado 31, faltam 2 caixas')
  await page.getByRole('button',{name:'Configurar capacidade de LESTE',exact:true}).click()
  const dialog=page.getByRole('dialog',{name:'Capacidade de LESTE',exact:true})
  await dialog.getByLabel('Capacidade física (caixas)',{exact:true}).fill('60');await dialog.getByRole('button',{name:'Salvar capacidade local'}).click()
  await expect(details).toContainText('Capacidade fictícia configurada: 60 caixas')
  await expect(details).toContainText('referência 33, contado 31, faltam 2 caixas')
  await page.getByLabel('Dados do gráfico de capacidade').selectOption('stock');await expect(map(page)).toHaveCount(0)
})
for(const theme of ['light','dark'])test(`mapa de apresentação em celular, teclado e auditoria A/AA ${theme}`,async({page})=>{
  await page.setViewportSize({width:375,height:812});const requests=[];page.on('request',request=>{if(request.url().includes('supabase.co'))requests.push(request.url())})
  await page.goto('/demonstracao.html')
  if(theme==='dark')await page.getByRole('button',{name:'Usar tema escuro'}).click()
  await expect(page.getByRole('heading',{name:'Apresentação do estoque',exact:true})).toBeVisible()
  await expect(page.getByText('Todos os dados desta página são fictícios.',{exact:true})).toBeVisible()
  await expect(page.getByRole('region',{name:'Indicadores fictícios'})).toContainText('85')
  await expect(page.getByLabel('Dados do gráfico de capacidade')).toHaveCount(0)
  await shelf(page,'NORTE').focus();await page.keyboard.press('Enter');await expect(shelf(page,'NORTE')).toHaveAttribute('aria-pressed','true')
  await map(page).getByRole('button',{name:'Fechar detalhes do mapa'}).click();await expect(shelf(page,'NORTE')).toBeFocused()
  const audit=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()
  expect(audit.violations.map(row=>({id:row.id,nodes:row.nodes.map(node=>node.target)}))).toEqual([])
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  expect(requests).toEqual([])
})
