import{test,expect}from'@playwright/test'
import AxeBuilder from'@axe-core/playwright'
import{prepareRedesign}from'./helpers/redesign'

for(const theme of ['light','dark'] as const){
 test(`Painel de referência ${theme}: grade, dados, fonte e contraste`,async({page})=>{
  await page.setViewportSize({width:1440,height:1000})
  const state=await prepareRedesign(page,theme)
  const shell=page.locator('.liber-layout')
  await expect(shell).toHaveCSS('background-color',theme==='light'?'rgb(251, 248, 245)':'rgb(31, 18, 11)')
  await expect(page.locator('main>.sidebar')).toHaveCSS('width','264px')
  await expect(page.getByRole('heading',{name:'Painel inicial',exact:true})).toHaveCSS('font-size','40px')
  expect(await page.evaluate(()=>document.fonts.check('600 16px Inter'))).toBe(true)
  await expect(page.locator('#dashboard-more')).not.toHaveAttribute('open')
  await expect(page.locator('.dashboard-stock-totals .dashboard-stat')).toHaveCount(4)
  const activity=await page.locator('.activity-panel').boundingBox(),sales=await page.locator('.dashboard-sales-panel').boundingBox(),receipt=await page.locator('.dashboard-receipts-panel').boundingBox()
  expect(Math.abs(activity!.y-sales!.y)).toBeLessThan(2)
  expect(receipt!.y).toBeGreaterThan(activity!.y+300)
  await page.screenshot({path:`test-results/painel-redesign-${theme}.png`,fullPage:true})
  const result=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()
  expect(result.violations).toEqual([])
  expect(state.errors).toEqual([]);expect(state.writes).toEqual([])
 })
}

