import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { prepareKeyboardPage } from './helpers/keyboard'
const panel = page => page.getByRole('region', { name: 'Divergências recorrentes', exact: true })
const key = 'liber:recurrence-rule:v1:presentation:11111111-1111-4111-8111-111111111111'
async function prepare(page) {
  const writes = await prepareKeyboardPage(page)
  const close = page.getByRole('button', { name: 'Fechar aviso de estoque', exact: true })
  if (await close.isVisible()) await close.click()
  await page.getByLabel('Visualização do Painel').selectOption('presentation')
  return writes
}
test('recorrência mostra evidências distintas e localiza a prateleira sem alterar estoque', async ({ page }) => {
  const writes = await prepare(page)
  await expect(panel(page)).toContainText('1 combinações com recorrência')
  await expect(panel(page)).toContainText('AGM-35 — LESTE')
  await expect(panel(page)).toContainText('Soma das diferenças absolutas: 6 caixas')
  await panel(page).getByText('Ver conferências de AGM-35 em LESTE', { exact:true }).click()
  await expect(panel(page)).toContainText('C-103 · 31/10/2026 · Esperado: 33 · Contado: 30 · Diferença: -3')
  await expect(panel(page)).toContainText('C-102 · 20/10/2026 · Esperado: 31 · Contado: 32 · Diferença: +1')
  await expect(panel(page)).not.toContainText('C-107'); await expect(panel(page)).not.toContainText('C-108')
  await panel(page).getByRole('button',{name:'Ver LESTE no mapa de recorrências'}).click()
  await expect(page.getByRole('region',{name:'Mapa de prateleiras',exact:true}).getByRole('button',{name:/^Prateleira LESTE —/})).toBeFocused()
  expect(writes).toEqual([])
})
test('configuração inclui molas com diferenças opostas e recupera período sem recorrências', async ({ page }) => {
  const writes = await prepare(page)
  await panel(page).getByLabel('Mínimo de conferências com diferença').fill('2')
  await panel(page).getByRole('button',{name:'Salvar regra de recorrência local'}).click()
  await expect(panel(page)).toContainText('2 combinações com recorrência')
  await expect(panel(page)).toContainText('MGM-35 — SUL')
  await expect(panel(page)).toContainText('Soma das diferenças absolutas: 2 caixas')
  await panel(page).getByLabel('Período de recorrência (dias corridos)').fill('7')
  await panel(page).getByRole('button',{name:'Salvar regra de recorrência local'}).click()
  await page.reload(); await page.getByLabel('Visualização do Painel').selectOption('presentation')
  await expect(panel(page)).toContainText('Nenhuma combinação atingiu a regra')
  await expect(panel(page).getByLabel('Mínimo de conferências com diferença')).toHaveValue('2')
  await expect(panel(page).getByLabel('Período de recorrência (dias corridos)')).toHaveValue('7')
  expect(writes).toEqual([])
})
test('falha ao salvar conserva regra aplicada e preenchimento',async({page})=>{
  await prepare(page)
  await page.evaluate(()=>{const original=Storage.prototype.setItem;Storage.prototype.setItem=function(k,v){if(k.startsWith('liber:recurrence-rule:'))throw Error('Sem espaço para regra');return original.call(this,k,v)}})
  await panel(page).getByLabel('Mínimo de conferências com diferença').fill('2')
  await panel(page).getByRole('button',{name:'Salvar regra de recorrência local'}).click()
  await expect(panel(page).getByRole('alert')).toContainText('Sem espaço para regra')
  await expect(panel(page)).toContainText('mínimo 3 conferências em 30 dias')
  await expect(panel(page).getByLabel('Mínimo de conferências com diferença')).toHaveValue('2')
})
test('regra ilegível é preservada e bloqueia a avaliação',async({page})=>{
  await prepare(page)
  await page.evaluate(k=>{localStorage.setItem(k,'inválido');window.dispatchEvent(new Event('liber:recurrence-rule'))},key)
  await expect(panel(page).getByRole('alert')).toContainText('avaliação bloqueada')
  await expect(panel(page).getByRole('list')).toHaveCount(0)
  await expect(panel(page).getByRole('form')).toHaveCount(0)
  expect(await page.evaluate(k=>localStorage.getItem(k),key)).toBe('inválido')
})
test('Consulta lê evidências sem receber edição da regra',async({page})=>{
  const writes=await prepare(page)
  await page.route('**/rest/v1/profiles*',route=>route.fulfill({json:{is_active:true,display_name:'Consulta',role:'viewer'}}))
  await page.reload();await page.getByLabel('Visualização do Painel').selectOption('presentation')
  await expect(panel(page)).toContainText('AGM-35 — LESTE')
  await expect(panel(page).getByRole('form')).toHaveCount(0)
  await panel(page).getByText('Ver conferências de AGM-35 em LESTE',{exact:true}).click()
  await expect(panel(page)).toContainText('C-103')
  expect(writes).toEqual([])
})
