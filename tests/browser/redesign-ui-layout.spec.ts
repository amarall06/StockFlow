import {expect, test} from '@playwright/test'
import {prepareKeyboardPage} from './helpers/keyboard'

test('layout compartilhado aplica os tokens do desktop e da gaveta nos dois temas', async ({page}) => {
  await page.setViewportSize({width:1920,height:1080})
  await page.emulateMedia({colorScheme:'dark'})
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await page.routeWebSocket('wss://stockflow-test.supabase.co/**', socket => socket.close())
  const writes = await prepareKeyboardPage(page)
  const notice = page.getByRole('button',{name:'Fechar aviso de estoque',exact:true})
  if (await notice.isVisible()) await notice.click()
  const shell = page.locator('.liber-layout')
  const desktopSidebar = shell.locator(':scope > .sidebar')
  await expect(shell).toHaveCSS('background-color','rgb(31, 18, 11)')
  await expect(desktopSidebar).toHaveCSS('width','264px')
  await expect(desktopSidebar).toHaveCSS('background-color','rgb(36, 23, 16)')

  await page.setViewportSize({width:360,height:800})
  await expect(desktopSidebar).toBeHidden()
  const menu = page.getByRole('button',{name:'Menu',exact:true})
  await menu.press('Enter')
  const drawer = page.getByRole('dialog',{name:'Menu de navegação'})
  await expect(drawer).toBeVisible()
  await expect(drawer).toHaveCSS('width','264px')
  await expect(drawer).toHaveCSS('background-color','rgb(36, 23, 16)')
  const close = drawer.getByRole('button',{name:'Fechar menu ×',exact:true})
  await expect(close).toHaveCSS('min-height','44px')
  await expect(close).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(menu).toBeFocused()

  await page.getByLabel('Opções da conta',{exact:true}).click()
  await page.getByRole('button',{name:'Ativar modo claro',exact:true}).click()
  await page.reload()
  await expect(shell).toHaveCSS('background-color','rgb(251, 248, 245)')
  if (await notice.isVisible()) await notice.click()
  await menu.press('Enter')
  await expect(drawer).toHaveCSS('background-color','rgb(51, 35, 27)')
  const alerts = drawer.getByRole('button',{name:/^Alertas/})
  await expect(alerts).toHaveAccessibleName(/produtos em alerta/)
  await alerts.click()
  await expect(page.getByRole('heading',{name:'Alertas',exact:true})).toBeVisible()
  await expect(drawer).toBeHidden()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(360)
  expect(errors).toEqual([])
  expect(writes).toEqual([])
})
