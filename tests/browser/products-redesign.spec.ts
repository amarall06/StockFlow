import{test,expect,type Page}from'@playwright/test'
import AxeBuilder from'@axe-core/playwright'
import{prepareRedesign}from'./helpers/redesign'
async function openProducts(page:Page){
 const trigger=page.getByRole('button',{name:'Menu',exact:true})
 if(await trigger.isVisible())await trigger.click()
 await page.locator('.sidebar:visible [data-page=products]').click()
 await expect(page.locator('.reference-products h1')).toHaveText('Produtos')
}
for(const theme of ['light','dark'] as const){
 test(`Produtos ${theme}: referência desktop, dados e acessibilidade`,async({page})=>{
  await page.setViewportSize({width:1440,height:1000})
  const state=await prepareRedesign(page,theme);await openProducts(page)
  await expect(page.getByRole('button',{name:'Todos (8)',exact:true})).toHaveAttribute('aria-pressed','true')
  const row=page.getByRole('row').filter({has:page.getByRole('button',{name:'Detalhes de AGM-35',exact:true})})
  await expect(row).toContainText('18 caixas');await expect(row).toContainText('10');await expect(row).toContainText('NORTE');await expect(row).toContainText('Adequado')
  await expect(page.getByRole('row').filter({hasText:'MFR-57'}).first()).toContainText('Abaixo do mínimo')
  await expect(page.getByRole('row').filter({hasText:'MGM-35'}).first()).toContainText('No limite')
  await expect(page.locator('.reference-products h1')).toHaveCSS('font-size','40px')
  await page.screenshot({path:`docs/design/produtos-${theme}.png`,fullPage:true})
  expect((await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()).violations).toEqual([])
  expect(state.errors).toEqual([]);expect(state.writes).toEqual([])
 })
 test(`Produtos ${theme}: celular preserva desenho e rola só a tabela`,async({page})=>{
  await page.setViewportSize({width:375,height:812})
  const state=await prepareRedesign(page,theme);await openProducts(page)
  const scroll=page.locator('.reference-products .ui-table-scroll')
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  expect(await scroll.evaluate(el=>el.scrollWidth>el.clientWidth)).toBe(true)
  await scroll.focus();await page.keyboard.press('ArrowRight')
  await expect.poll(()=>scroll.evaluate(el=>el.scrollLeft)).toBeGreaterThan(0)
  await scroll.evaluate(el=>{el.scrollLeft=0})
  await expect(page.getByRole('button',{name:'Todos (8)',exact:true})).toBeVisible()
  const targets=await page.locator('.reference-products button:visible,.reference-products summary:visible,.reference-products input:visible').evaluateAll(els=>els.map(el=>el.getBoundingClientRect().height))
  expect(targets.every(height=>height>=44)).toBe(true)
  await page.screenshot({path:`docs/design/produtos-${theme}-mobile.png`,fullPage:true})
  expect((await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()).violations).toEqual([])
  expect(state.errors).toEqual([]);expect(state.writes).toEqual([])
 })
}
