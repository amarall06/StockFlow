test('Produtos: acabamento tipográfico, menus por teclado e capturas finais',async({browser})=>{
 for(const theme of ['light','dark'] as const)for(const mobile of [false,true]){
  const context=await browser.newContext({viewport:mobile?{width:375,height:812}:{width:1440,height:1000},baseURL:test.info().project.use.baseURL})
  try{
   const page=await context.newPage(),state=await prepareRedesign(page,theme);await openProducts(page)
   await expect(page.locator('.reference-products tbody td').first()).toHaveCSS('font-size','14px')
   await expect(page.locator('.reference-products thead')).toHaveCSS('background-color','rgba(0, 0, 0, 0)')
   const create=page.locator('.products-create summary');await create.focus();await page.keyboard.press('Enter')
   await expect(page.locator('.products-create')).toHaveAttribute('open','')
   const box=await page.locator('.products-create>div').boundingBox()
   expect(box!.x).toBeGreaterThanOrEqual(0);expect(box!.x+box!.width).toBeLessThanOrEqual(mobile?375:1440)
   await page.keyboard.press('Enter');await page.locator('.reference-products h1').click()
   await page.screenshot({path:`docs/design/produtos-${theme}${mobile?'-mobile':''}.png`,fullPage:true})
   expect(state.errors).toEqual([]);expect(state.writes).toEqual([])
  }finally{await context.close()}
 }
})
