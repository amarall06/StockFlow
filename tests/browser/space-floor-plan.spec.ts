import {test,expect} from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import {prepareKeyboardPage} from './helpers/keyboard'
async function prepare(page){const writes=await prepareKeyboardPage(page);const close=page.getByRole('button',{name:'Fechar aviso de estoque',exact:true});if(await close.isVisible())await close.click();await page.getByLabel('Visualização do Painel').selectOption('presentation');return writes}
const suggestions=page=>page.getByRole('region',{name:'Sugestões de espaço',exact:true})
const map=page=>page.getByRole('region',{name:'Mapa de prateleiras',exact:true})
test('apresentação está no site original com textos normais e sem link para outra página',async({page})=>{
  const writes=await prepare(page)
  await expect(page.getByRole('region',{name:'Indicadores do estoque'})).toContainText('85')
  expect(await page.locator('#consulta').innerText()).not.toMatch(/fictíci[oa]/i)
  await expect(page.locator('#consulta a[href="/demonstracao.html"]')).toHaveCount(0)
  await expect(map(page).getByRole('region',{name:'Área da planta com rolagem'})).toBeVisible()
  await expect(map(page).getByText('Recebimento',{exact:true})).toBeVisible();await expect(map(page).getByText('Expedição',{exact:true})).toBeVisible()
  expect(writes).toEqual([])
})
test('amortecedores são sugeridos para Oeste, com motivos de exclusão e seleção no mapa',async({page})=>{
  const writes=await prepare(page),section=suggestions(page)
  await section.getByRole('button',{name:'Sugerir espaços'}).click()
  await expect(section.getByRole('status')).toContainText('1 prateleiras')
  await expect(section.getByRole('button',{name:'Ver OESTE no mapa'})).toBeVisible()
  await section.getByText('Por que as outras prateleiras não foram sugeridas?',{exact:true}).click()
  await expect(section).toContainText('Divergência de contagem pendente')
  await section.getByRole('button',{name:'Ver OESTE no mapa'}).click()
  const west=map(page).getByRole('button',{name:/^Prateleira OESTE —/})
  await expect(west).toHaveAttribute('aria-pressed','true');await expect(west).toBeFocused()
  await expect(map(page).getByRole('region',{name:'Detalhes da prateleira'})).toContainText('Prateleira OESTE')
  expect(writes).toEqual([])
})
test('molas respeitam espaço conferido e ranking; quantidade sem destino não gera sugestão parcial',async({page})=>{
  await prepare(page);const section=suggestions(page)
  await section.getByLabel('Categoria para armazenar').selectOption('spring')
  await expect(section.getByLabel('Situação para armazenar').locator('option')).toHaveText(['Em estoque'])
  await section.getByRole('button',{name:'Sugerir espaços'}).click()
  await expect(section.locator('.space-results>li>strong')).toHaveText(['SUL','OESTE'])
  await section.getByLabel('Caixas a acomodar').fill('35');await section.getByRole('button',{name:'Sugerir espaços'}).click()
  await expect(section.locator('.space-results>li>strong')).toHaveText(['OESTE'])
  await section.getByLabel('Caixas a acomodar').fill('41');await section.getByRole('button',{name:'Sugerir espaços'}).click()
  await expect(section.getByRole('status')).toContainText('Nenhuma prateleira comporta toda a quantidade')
  await expect(section.locator('.space-results>li')).toHaveCount(0)
})
test('sugestão é recalculada quando a capacidade local diminui',async({page})=>{
  await prepare(page);const section=suggestions(page)
  await section.getByRole('button',{name:'Sugerir espaços'}).click()
  await page.getByRole('button',{name:'Configurar capacidade de OESTE',exact:true}).click()
  const dialog=page.getByRole('dialog',{name:'Capacidade de OESTE',exact:true})
  await dialog.getByLabel('Capacidade física (caixas)',{exact:true}).fill('5');await dialog.getByRole('button',{name:'Salvar capacidade local'}).click()
  await expect(section.getByRole('status')).toContainText('Nenhuma prateleira')
})
test('posição e dimensões são aplicadas e recuperadas ao reabrir; sobreposição é recusada',async({page})=>{
  const writes=await prepare(page)
  await map(page).getByRole('button',{name:/^Prateleira NORTE —/}).click()
  const form=page.getByRole('form',{name:'Posição de NORTE'})
  await form.getByLabel('Coluna X de NORTE',{exact:true}).fill('20');await form.getByLabel('Linha Y de NORTE',{exact:true}).fill('2')
  await form.getByRole('button',{name:'Aplicar posição'}).click()
  await map(page).getByRole('button',{name:'Salvar planta local'}).click()
  await expect(map(page).getByRole('status').filter({hasText:'Planta salva'})).toBeVisible()
  await page.reload();await page.getByLabel('Visualização do Painel').selectOption('presentation')
  await map(page).getByRole('button',{name:/^Prateleira NORTE —/}).click()
  await expect(page.getByLabel('Coluna X de NORTE',{exact:true})).toHaveValue('20')
  await expect(page.getByLabel('Linha Y de NORTE',{exact:true})).toHaveValue('2')
  await page.getByLabel('Coluna X de NORTE',{exact:true}).fill('5');await page.getByLabel('Linha Y de NORTE',{exact:true}).fill('12')
  await page.getByRole('form',{name:'Posição de NORTE'}).getByRole('button',{name:'Aplicar posição'}).click()
  await expect(page.getByRole('form',{name:'Posição de NORTE'}).getByRole('alert')).toContainText('sobrepostas')
  expect(writes).toEqual([])
})
for(const theme of ['light','dark'])test(`planta e sugestão em 375 px, teclado, zoom e auditoria A/AA ${theme}`,async({page})=>{
  await page.setViewportSize({width:375,height:812});await page.addInitScript(value=>localStorage.setItem('liber-automotive-theme',value),theme)
  await prepare(page)
  await map(page).getByRole('button',{name:'Ampliar planta'}).click();await expect(map(page).getByLabel('Nível de zoom')).toHaveText('100%')
  await suggestions(page).getByRole('button',{name:'Sugerir espaços'}).click();const see=suggestions(page).getByRole('button',{name:'Ver OESTE no mapa'});await see.focus();await page.keyboard.press('Enter')
  await expect(map(page).getByRole('button',{name:/^Prateleira OESTE —/})).toBeFocused()
  const audit=await new AxeBuilder({page}).include('.stock-presentation').withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()
  expect(audit.violations.map(row=>({id:row.id,nodes:row.nodes.map(node=>({target:node.target,summary:node.failureSummary}))}))).toEqual([])
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
})
